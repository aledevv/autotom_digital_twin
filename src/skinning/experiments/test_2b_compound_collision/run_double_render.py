import math
import os
import sys
import time

from isaacsim import SimulationApp

simulation_app = SimulationApp({
    "headless": False,
    "width": 1280,
    "height": 720,
})

import omni.usd
from omni.physx import get_physx_interface
from isaacsim.core.api import World
from pxr import Gf, Usd, UsdGeom, UsdSkel, Vt

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
if SCRIPT_DIR not in sys.path:
    sys.path.insert(0, SCRIPT_DIR)

import generate_double_render as asset

SKEL_ROOT_PATH = "/World/StemVisual/SkelRoot"
ANIMATION_PATH = "/World/StemVisual/SkelRoot/SkelAnim"


def get_world_mats(cache, prims):
    cache.Clear()
    return [Gf.Matrix4d(cache.GetLocalToWorldTransform(p)) for p in prims]


def world_to_joint_local(world_mats, skel_root_world):
    local_mats = []
    for i, world in enumerate(world_mats):
        if i == 0:
            local = world * skel_root_world.GetInverse()
        else:
            local = world * world_mats[i - 1].GetInverse()
        local_mats.append(local)
    return local_mats


def decompose(local_mats):
    translations = []
    rotations = []

    for m in local_mats:
        t = m.ExtractTranslation()
        q = m.ExtractRotationQuat()
        qi = q.GetImaginary()

        translations.append(Gf.Vec3f(float(t[0]), float(t[1]), float(t[2])))
        rotations.append(
            Gf.Quatf(
                float(q.GetReal()),
                Gf.Vec3f(float(qi[0]), float(qi[1]), float(qi[2])),
            )
        )

    return Vt.Vec3fArray(translations), Vt.QuatfArray(rotations)


def sync_skin(cache, link_prims, skel_root_world, translations_attr, rotations_attr):
    world_mats = get_world_mats(cache, link_prims)
    local_mats = world_to_joint_local(world_mats, skel_root_world)
    translations, rotations = decompose(local_mats)
    translations_attr.Set(translations)
    rotations_attr.Set(rotations)
    return world_mats, local_mats


def translation_error(a, b):
    return float((a.ExtractTranslation() - b.ExtractTranslation()).GetLength())


def rotation_error_deg(a, b):
    relative = a * b.GetInverse()
    angle = abs(float(relative.ExtractRotation().GetAngle()))
    if angle > 180.0:
        angle = 360.0 - angle
    return angle


def main():
    print()
    print("=" * 80)
    print("TEST 2B-E — Double render without extra physics")
    print("=" * 80)
    print(f"SYNC PRESET: {asset.SYNC_PRESET}")
    print(
        f"physics={asset.NUM_LINKS} links/bones | "
        f"rings={len(asset.CENTERLINE['positions'])} | "
        f"radial={asset.BRANCH_SPEC.radial_segments} | "
        f"capsules={asset.NUM_LINKS * asset.BRANCH_SPEC.colliders_per_link}"
    )
    print("=" * 80)

    asset.build_stage(asset.OUTPUT_USD)

    ctx = omni.usd.get_context()
    ctx.open_stage(asset.OUTPUT_USD)

    if World.instance() is not None:
        World.instance().clear_instance()

    world = World(
        stage_units_in_meters=1.0,
        physics_prim_path="/World/PhysicsScene",
    )

    stage = ctx.get_stage()
    link_prims = [stage.GetPrimAtPath(path) for path in asset.LINK_PATHS]

    for path, prim in zip(asset.LINK_PATHS, link_prims):
        if not prim.IsValid():
            raise RuntimeError(f"Missing generated rigid link: {path}")

    skel_root = stage.GetPrimAtPath(SKEL_ROOT_PATH)
    animation_prim = stage.GetPrimAtPath(ANIMATION_PATH)

    if not skel_root.IsValid():
        raise RuntimeError("Missing SkelRoot")
    if not animation_prim.IsValid():
        raise RuntimeError("Missing SkelAnimation")

    animation = UsdSkel.Animation(animation_prim)
    translations_attr = animation.GetTranslationsAttr()
    rotations_attr = animation.GetRotationsAttr()

    cache = UsdGeom.XformCache(Usd.TimeCode.Default())
    cache.Clear()
    skel_root_world = Gf.Matrix4d(cache.GetLocalToWorldTransform(skel_root))

    # Generic frame-0 verification for arbitrary link count.
    actual_rest = world_to_joint_local(
        get_world_mats(cache, link_prims),
        skel_root_world,
    )
    expected_rest = asset.rest_local_transforms()

    print()
    print("[PARAMETRIC REST-FRAME CHECK]")
    max_t = 0.0
    max_r = 0.0

    for i, (actual, expected) in enumerate(zip(actual_rest, expected_rest)):
        te = translation_error(actual, expected)
        re = rotation_error_deg(actual, expected)
        max_t = max(max_t, te)
        max_r = max(max_r, re)
        print(
            f"  Bone{i:02d}: translation={te * 1000.0:.6f} mm  "
            f"rotation={re:.6f} deg"
        )

    print(f"  max: {max_t * 1000.0:.6f} mm, {max_r:.6f} deg")
    if max_t < 1e-5 and max_r < 1e-4:
        print("  [OK] generated PhysX and Skeleton rest frames coincide.")
    else:
        print("  [WARNING] generated rest-frame mismatch.")

    world.reset()

    sync_skin(
        cache,
        link_prims,
        skel_root_world,
        translations_attr,
        rotations_attr,
    )

    print()
    print("[WHAT TEST 2A MUST PROVE]")
    print(f"  requested physics links : {asset.BRANCH_SPEC.physics_links}")
    print(f"  generated rigid links   : {len(asset.PHYSICS['origins'])}")
    print(f"  generated bones         : {asset.NUM_BONES}")
    print(f"  generated D6 joints     : {asset.NUM_LINKS - 1}")
    print(f"  visual rings            : {len(asset.CENTERLINE['positions'])}")
    print()
    print("  GO if:")
    print("    [ ] smooth 3D rest shape")
    print("    [ ] no startup snap")
    print("    [ ] all generated links move as one articulation")
    print("    [ ] BranchMesh follows all generated bones")
    print("    [ ] taper / swellings remain coherent")
    print("    [ ] ground contact remains stable")
    print()
    print()
    print("[2B-E HYPOTHESIS]")
    print("  D still had visible startup delay.")
    print("  E keeps the exact same physics and skin workload.")
    print("  Only the presentation phase changes:")
    print("    physics -> PhysX/USD sync -> skin -> render -> render")
    print("  There is NO extra physics step between the two renders.")
    print()
    print("  Interpretation:")
    print("    delay disappears  -> UsdSkel/render evaluation latency")
    print("    delay unchanged   -> not fixed by an extra render evaluation")
    print()
    print("No need to press Play.")
    print("=" * 80)

    # Explicit PhysX -> USD transform write-back interface.
    physx_interface = get_physx_interface()

    step = 0
    last_log = 0
    start = time.time()

    physics_acc = 0.0
    transform_sync_acc = 0.0
    sync_acc = 0.0
    render1_acc = 0.0
    render2_acc = 0.0
    total_acc = 0.0
    profile_count = 0

    while simulation_app.is_running():
        frame_t0 = time.perf_counter()

        t0 = time.perf_counter()
        world.step(render=False)
        t1 = time.perf_counter()

        # --------------------------------------------------------------
        # TEST 2B-D CHANGE:
        # force the post-simulation PhysX transforms into fast cache + USD
        # BEFORE UsdGeom.XformCache is queried by sync_skin().
        # --------------------------------------------------------------
        physx_interface.update_transformations(
            True,   # updateToFastCache
            True,   # updateToUsd
            False,  # updateVelocitiesToUsd
        )
        t_sync = time.perf_counter()

        world_mats, local_mats = sync_skin(
            cache,
            link_prims,
            skel_root_world,
            translations_attr,
            rotations_attr,
        )
        t2 = time.perf_counter()

        # --------------------------------------------------------------
        # TEST 2B-E CHANGE:
        # render twice WITHOUT advancing physics between the two renders.
        #
        # If render #2 makes the skin catch up to the colliders, the lag
        # is in UsdSkel/render evaluation rather than in the physics pose.
        # --------------------------------------------------------------
        world.render()
        t_render1 = time.perf_counter()

        world.render()
        t3 = time.perf_counter()

        physics_acc += t1 - t0
        transform_sync_acc += t_sync - t1
        sync_acc += t2 - t_sync
        render1_acc += t_render1 - t2
        render2_acc += t3 - t_render1
        total_acc += t3 - frame_t0
        profile_count += 1

        step += 1

        if step - last_log >= 240:
            last_world = world_mats[-1]
            last_length = float(asset.PHYSICS["lengths"][-1])
            last_tip = last_world.Transform(
                Gf.Vec3d(0.0, 0.0, last_length)
            )

            ms = 1000.0 / max(profile_count, 1)

            print(
                f"[frame {step:6d}] "
                f"tip=({last_tip[0]:+.3f},"
                f"{last_tip[1]:+.3f},"
                f"{last_tip[2]:+.3f})"
            )
            print(
                f"             avg {profile_count} frames | "
                f"physics={physics_acc * ms:.3f} ms | "
                f"physx->USD={transform_sync_acc * ms:.3f} ms | "
                f"sync_skin={sync_acc * ms:.3f} ms | "
                f"render1={render1_acc * ms:.3f} ms | "
                f"render2={render2_acc * ms:.3f} ms | "
                f"total={total_acc * ms:.3f} ms"
            )

            physics_acc = 0.0
            transform_sync_acc = 0.0
            sync_acc = 0.0
            render1_acc = 0.0
            render2_acc = 0.0
            total_acc = 0.0
            profile_count = 0
            last_log = step

    elapsed = time.time() - start
    print()
    print("=" * 80)
    print(f"Finished: {step} frames in {elapsed:.1f}s")
    print("TEST 2B-B = GO if rounded compound capsules improve ground contact without changing articulation resolution.")
    print("=" * 80)

    simulation_app.close()


if __name__ == "__main__":
    try:
        main()
    finally:
        if simulation_app.is_running():
            simulation_app.close()
