def run_all_tests() -> tuple:
    """
    Run all 9 geometric consistency tests and collect results.
    
    Returns:
        Tuple of (all_passed, test_results, global_max_error)
        where test_results is a list of (test_name, max_error, passed, description)
    """
    test_suite = [
        (1, "trunk_vertical", test_trunk_vertical, 
         "10 vertical links, no branches"),
        (2, "single_branch_45deg", test_single_branch_45deg,
         "Trunk + branch at 45° tilt"),
        (3, "branch_attach_first_link", test_branch_attach_first_link,
         "Branch attached to first trunk link"),
        (4, "branch_attach_last_link", test_branch_attach_last_link,
         "Branch attached to last trunk link"),
        (5, "sub_branch_nested", test_sub_branch_nested,
         "Depth-3 nesting: trunk→branchA→subA1"),
        (6, "multiple_branches_azimuth", test_multiple_branches_azimuth,
         "4 branches forming cross (0°/90°/180°/270°)"),
        (7, "tiny_radius_branch", test_tiny_radius_branch,
         "1mm radius - numerical stability"),
        (8, "horizontal_branch", test_horizontal_branch,
         "90° tilt - perpendicular orientation"),
        (9, "near_vertical_branch", test_near_vertical_branch,
         "1° tilt - small angle preservation"),
    ]
    
    test_results = []
    all_passed = True
    
    for test_num, test_name, test_func, description in test_suite:
        try:
            max_error = test_func(test_num)
            passed = max_error < 1.0
            test_results.append((test_name, max_error, passed, description))
            if not passed:
                all_passed = False
        except AssertionError as e:
            test_results.append((test_name, None, False, description))
            all_passed = False
            print(f"  ❌ FAILED: {e}")
        except Exception as e:
            test_results.append((test_name, None, False, description))
            all_passed = False
            print(f"  ❌ ERROR: {e}")
            import traceback
            traceback.print_exc()
    
    # Calculate global max error
    valid_errors = [err for _, err, _, _ in test_results if err is not None]
    global_max_error = max(valid_errors) if valid_errors else None
    
    return all_passed, test_results, global_max_error


