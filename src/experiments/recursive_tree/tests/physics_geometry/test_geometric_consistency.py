def compute_expected_position(
    branch_def: dict,
    link_index: int,
    parent_base_world: Gf.Vec3d = None,
    parent_axis: Gf.Vec3d = None,
    parent_info: dict = None,
    parent_orientation: Gf.Quatf = None,
) -> Gf.Vec3d:
    """
    Calculate expected world-space position for a link in a branch.
    
    Args:
        branch_def: Branch definition dict from BRANCHES list
        link_index: 0-based index of link in this branch
        parent_base_world: Parent link attachment base position (None for trunk)
        parent_axis: Parent chain axis in world space (None for trunk)
        parent_info: Dict with 'radius', 'height' of parent (None for trunk)
        parent_orientation: Parent's world-space orientation quaternion (None for trunk)
    
    Returns:
        Expected world-space position as Gf.Vec3d
    """
    r_world = scaled(branch_def["radius"])
    h_world = scaled(branch_def["height"])
    gap = scaled(GAP)
    
    # For trunk (vertical chain starting at origin)
    if parent_base_world is None:
        # Trunk is vertical, links stacked along Z
        z_offset = link_index * (h_world + gap)
        return Gf.Vec3d(0.0, 0.0, z_offset)
    
    # For branch attached to parent
    tilt_deg = branch_def["tilt"]
    rot_deg = branch_def["rot"]
    
    # 1. Compute branch axis in world space (same logic as generator)
    # First tilt, then azimuth rotation in parent frame
    rot_z = Gf.Rotation(Gf.Vec3d(0, 0, 1), rot_deg)
    rot_tilt = Gf.Rotation(Gf.Vec3d(1, 0, 0), -tilt_deg)
    branch_rot_in_parent_frame = rot_tilt * rot_z
    
    # Transform to world space using parent orientation
    if parent_orientation is None:
        parent_orientation = Gf.Quatf(1, 0, 0, 0)  # identity
    
    parent_rot = Gf.Rotation(Gf.Quatd(parent_orientation))
    combined = branch_rot_in_parent_frame * parent_rot
    
    branch_axis_raw = combined.TransformDir(Gf.Vec3d(0, 0, 1))
    branch_axis = Gf.Vec3d(*branch_axis_raw).GetNormalized()
    
    # 2. Compute branch base position (attachment point)
    p_r_world = parent_info["radius"]
    p_h_world = parent_info["height"]
    
    # Radial offset in parent's local frame
    radial_distance = p_r_world / 2.0
    base_offset_local = Gf.Vec3d(0.0, radial_distance, p_h_world + gap)
    
    # Apply azimuth rotation in parent frame
    rot_z_local = Gf.Rotation(Gf.Vec3d(0, 0, 1), rot_deg)
    offset_in_parent_frame = rot_z_local.TransformDir(base_offset_local)
    
    # Transform to world space
    offset_in_world = parent_rot.TransformDir(offset_in_parent_frame)
    
    # Branch base = parent attachment point + offset
    branch_base = parent_base_world + offset_in_world
    
    # 3. Position of this specific link along branch axis
    link_offset = link_index * (h_world + gap)
    link_pos = branch_base + (branch_axis * link_offset)
    
    return link_pos


def read_link_position_from_usd(stage: Usd.Stage, link_path: str) -> Gf.Vec3d:
    """
    Read the world-space position of a link from the USD stage.
    
    Args:
        stage: USD stage
        link_path: Path to link Xform (e.g., "/World/Stem/trunk_Link_01")
    
    Returns:
        Position as Gf.Vec3d from xformOp:translate
    """
    prim = stage.GetPrimAtPath(link_path)
    if not prim.IsValid():
        raise ValueError(f"Invalid prim at path: {link_path}")
    
    xform = UsdGeom.Xform(prim)
    translate_op = None
    
    # Find the translate operation
    for op in xform.GetOrderedXformOps():
        if op.GetOpType() == UsdGeom.XformOp.TypeTranslate:
            translate_op = op
            break
    
    if translate_op is None:
        raise ValueError(f"No translate op found for {link_path}")
    
    pos = translate_op.Get()
    return Gf.Vec3d(pos[0], pos[1], pos[2])


def verify_branch_geometry(
    stage: Usd.Stage,
    branch_def: dict,
    parent_base_world: Gf.Vec3d = None,
    parent_axis: Gf.Vec3d = None,
    parent_info: dict = None,
    parent_orientation: Gf.Quatf = None,
) -> list:
    """
    Verify all links in a branch match expected positions.
    
    Args:
        stage: USD stage
        branch_def: Branch definition dict
        parent_base_world: Parent attachment base (None for trunk)
        parent_axis: Parent chain axis (None for trunk)
        parent_info: Parent dimensions (None for trunk)
        parent_orientation: Parent orientation quaternion (None for trunk)
    
    Returns:
        List of tuples: (link_name, actual_pos, expected_pos, error_mm)
    """
    results = []
    bid = branch_def["id"]
    n_links = branch_def["n_links"]
    stem_path = "/World/Stem"
    
    for i in range(n_links):
        link_name = f"{bid}_Link_{i + 1:02d}"
        link_path = f"{stem_path}/{link_name}"
        
        # Read actual position from USD
        actual_pos = read_link_position_from_usd(stage, link_path)
        
        # Compute expected position
        expected_pos = compute_expected_position(
            branch_def, i,
            parent_base_world, parent_axis, parent_info, parent_orientation
        )
        
        # Calculate error in mm
        diff = actual_pos - expected_pos
        error_mm = math.sqrt(diff[0]**2 + diff[1]**2 + diff[2]**2) * 1000.0
        
        results.append((link_name, actual_pos, expected_pos, error_mm))
    
    return results


