def print_test_header(test_num: int, test_name: str, description: str) -> None:
    """Print formatted header for a test case."""
    print()
    print(f"Test {test_num}: {test_name}")
    print(f"  {description}")


def print_link_result(link_name: str, error_mm: float, threshold: float = 1.0) -> None:
    """Print result for a single link with checkmark or cross."""
    status = "✓" if error_mm < threshold else "✗"
    print(f"  {link_name:25s} error {error_mm:6.3f} mm {status}")


def print_test_summary(test_name: str, max_error: float, passed: bool) -> None:
    """Print summary for a test case."""
    status = "PASS" if passed else "FAIL"
    symbol = "✅" if passed else "❌"
    print(f"  → {status} (max error: {max_error:.3f} mm) {symbol}")


def build_and_verify_config(test_name: str, branches: list) -> tuple:
    """
    Build a USD from custom branches config and verify all link positions.
    
    This is the main orchestration function for each test:
    1. Validates the branches configuration
    2. Creates a temporary USD file
    3. Builds the stage using the generator
    4. Verifies all branch geometries
    5. Cleans up the temporary file
    
    Args:
        test_name: Name of the test (for error messages)
        branches: List of branch definition dicts
    
    Returns:
        Tuple of (max_error_mm, results_dict)
        where results_dict maps branch_id -> list of verification results
    """
    # Validate configuration
    try:
        validate_branches(branches)
    except ValueError as e:
        raise ValueError(f"[{test_name}] Invalid configuration: {e}")
    
    # Create temporary USD file
    temp_fd, temp_path = tempfile.mkstemp(suffix=".usda", prefix=f"test_{test_name}_")
    os.close(temp_fd)  # Close file descriptor, we'll use the path
    
    try:
        # Build the stage
        stage, stem_path = build_stage(temp_path, branches)
        
        # We need to track parent info for nested branches
        # branch_id -> (base_world_pos, axis, info_dict, orientation)
        branch_info = {}
        
        # Build registry of branch info as we process them
        # We must process in order (parent before children)
        results_dict = {}
        max_error = 0.0
        
        for branch_def in branches:
            bid = branch_def["id"]
            is_root = branch_def.get("parent") is None
            
            if is_root:
                # Trunk - starts at origin, vertical
                parent_base_world = None
                parent_axis = None
                parent_info = None
                parent_orientation = None
            else:
                # Branch - get parent info
                parent_id = branch_def["parent"]
                attach_idx = branch_def["attach_link"] - 1  # 0-based
                
                if parent_id not in branch_info:
                    raise ValueError(
                        f"[{test_name}] Parent '{parent_id}' must be defined before '{bid}'"
                    )
                
                parent_bases, parent_axis, parent_info_dict, parent_orientation = branch_info[parent_id]
                parent_base_world = parent_bases[attach_idx]
                parent_axis = parent_axis
                parent_info = parent_info_dict
            
            # Verify this branch's geometry
            branch_results = verify_branch_geometry(
                stage, branch_def,
                parent_base_world, parent_axis, parent_info, parent_orientation
            )
            
            results_dict[bid] = branch_results
            
            # Update max error
            for _, _, _, error_mm in branch_results:
                max_error = max(max_error, error_mm)
            
            # Store info for potential child branches
            # We need to compute the base positions and axis for this branch
            r_world = scaled(branch_def["radius"])
            h_world = scaled(branch_def["height"])
            gap = scaled(GAP)
            n_links = branch_def["n_links"]
            
            # Compute base positions for all links in this branch
            link_bases = []
            for i in range(n_links):
                expected_pos = compute_expected_position(
                    branch_def, i,
                    parent_base_world, parent_axis, parent_info, parent_orientation
                )
                link_bases.append(expected_pos)
            
            # Compute branch axis (same logic as in compute_expected_position)
            if is_root:
                branch_axis = Gf.Vec3d(0, 0, 1)
                branch_orientation = Gf.Quatf(1, 0, 0, 0)
            else:
                tilt_deg = branch_def["tilt"]
                rot_deg = branch_def["rot"]
                
                rot_z = Gf.Rotation(Gf.Vec3d(0, 0, 1), rot_deg)
                rot_tilt = Gf.Rotation(Gf.Vec3d(1, 0, 0), -tilt_deg)
                branch_rot_in_parent_frame = rot_tilt * rot_z
                
                if parent_orientation is None:
                    parent_orientation = Gf.Quatf(1, 0, 0, 0)
                
                parent_rot = Gf.Rotation(Gf.Quatd(parent_orientation))
                combined = branch_rot_in_parent_frame * parent_rot
                
                branch_axis_raw = combined.TransformDir(Gf.Vec3d(0, 0, 1))
                branch_axis = Gf.Vec3d(*branch_axis_raw).GetNormalized()
                
                branch_orientation = Gf.Quatf(combined.GetQuat())
            
            branch_info[bid] = (
                link_bases,
                branch_axis,
                {"radius": r_world, "height": h_world},
                branch_orientation
            )
        
        return max_error, results_dict
        
    finally:
        # Cleanup temporary file
        try:
            os.unlink(temp_path)
        except Exception:
            pass  # Ignore cleanup errors


